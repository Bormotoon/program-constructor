/**
 * Изменения годовой нормы часов, которых ещё нет в разобранных ФРП.
 *
 * Каталог собран из официальных ФРП 2025 г. (edsoo.ru), а приказ Минпросвещения
 * России от 10.11.2025 № 808 сократил иностранный язык уже после их публикации:
 * с 3 часов в неделю (102 часа) до 2 (68 часов) — в 5 классе с 1 сентября
 * 2026 г., в 6 и 7 классах с 1 сентября 2027 г. В 8 и 9 классах норма прежняя.
 *
 * Источник — приложение к письму Минпросвещения России от 02.03.2026 № 03-320
 * «Информация об изменениях в ФООП»: «Скорректировано общее число часов,
 * рекомендованных для изучения иностранного языка, — 408 часов: в 5 классе —
 * 68 часов (2 часа в неделю), в 6 классе — 68 часов (2 часа в неделю)
 * (в 2026/2027 учебном году остается 102 часа (3 часа в неделю), в 7 классе —
 * 68 часов (2 часа в неделю) (в 2026/2027 учебном году остается 102 часа
 * (3 часа в неделю), в 8 классе — 102 часа (3 часа в неделю), в 9 классе —
 * 102 часа (3 часа в неделю)».
 *
 * **Конструктор не решает за учителя.** По умолчанию подставляется норма,
 * действующая на сегодня: пока приказ в силу не вступил — прежняя. Оба числа,
 * старое и новое, считаются допустимыми: расхождение не помечается ошибкой,
 * а рядом висит предупреждение со ссылкой на документ. Сколько часов встанет
 * в программу, решает учитель — по учебному плану своей школы.
 *
 * Тематическое планирование остаётся прежним: новую редакцию ФРП с разбивкой
 * на 68 часов edsoo.ru не выложил, а придумывать распределение по темам за
 * министерство нельзя. Когда ФРП выйдет, разбор даст верные цифры сам и этот
 * файл нужно будет почистить.
 *
 * Второй иностранный язык — отдельный учебный предмет, приказ его не касается:
 * там и было 68 часов.
 */

/** ФРП учебного предмета «Иностранный язык» на уровне ООО. */
const FOREIGN_LANGUAGE_OOO = new Set([
  'inostrannyj-anglijskij-yazyk-ooo',
  'inostrannyj-nemeckij-yazyk-ooo',
]);

/** Класс → дата, с которой иностранный язык идёт по 2 часа в неделю. */
const TWO_HOURS_SINCE: Record<number, string> = {
  5: '2026-09-01',
  6: '2027-09-01',
  7: '2027-09-01',
};

const WAS = 102;
const BECOMES = 68;

/** Приложение к письму — там изменение расписано по классам. */
export const HOURS_DOC_URL =
  'https://edsoo.ru/wp-content/uploads/2026/03/03-320-prilozhenie-versiya-2.pdf';

export interface HoursChange {
  /** Норма на сегодня — её конструктор и подставляет. */
  hours: number;
  /** Второе допустимое значение: норма по другую сторону от даты. */
  alsoAllowed: number;
  /** Приказ уже действует. */
  inForce: boolean;
  /** Дата вступления в силу, «01.09.2026». */
  since: string;
  /** Предупреждение для учителя. */
  text: string;
}

function ru(date: string): string {
  const [y, m, d] = date.split('-');
  return `${d}.${m}.${y}`;
}

/**
 * Изменение нормы часов для предмета и класса; null — ничего не менялось.
 *
 * Дата передаётся параметром, чтобы поведение до и после вступления приказа
 * в силу можно было проверить, не переводя часы на машине.
 */
export function hoursChange(
  slug: string,
  grade: number,
  today: Date = new Date(),
): HoursChange | null {
  if (!FOREIGN_LANGUAGE_OOO.has(slug)) return null;
  const date = TWO_HOURS_SINCE[grade];
  if (!date) return null;

  const inForce = today >= new Date(`${date}T00:00:00`);
  const since = ru(date);
  return {
    hours: inForce ? BECOMES : WAS,
    alsoAllowed: inForce ? WAS : BECOMES,
    inForce,
    since,
    text:
      `С ${since} иностранный язык в ${grade} классе — 2 часа в неделю, ` +
      `${BECOMES} часов в год вместо ${WAS} (приказ Минпросвещения России ` +
      'от 10.11.2025 № 808, письмо от 02.03.2026 № 03-320). ' +
      (inForce
        ? `Подставлена новая норма — ${BECOMES} ч. `
        : `Пока подставлена действующая норма — ${WAS} ч. `) +
      `Федеральная рабочая программа с планированием на ${BECOMES} часов ещё ` +
      'не опубликована, поэтому таблица заполняется прежней. Сверьтесь ' +
      'с учебным планом своей школы: и ' +
      `${WAS}, и ${BECOMES} часов конструктор считает допустимыми, ` +
      'сколько поставить — решаете вы.',
  };
}
