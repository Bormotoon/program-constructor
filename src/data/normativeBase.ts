/**
 * Нормативная база рабочей программы.
 *
 * Это единственный текстовый раздел, которого в ФРП нет: там не перечисляют
 * приказы, которыми утверждены ФГОС и ФОП. Пояснительная записка, содержание
 * обучения и планируемые результаты берутся из самих федеральных программ
 * (tools/frp_content.py), поэтому прежний генератор с рукописной базой на пять
 * предметов и типовыми формулировками для остальных удалён: официальный текст
 * есть у всех 65 программ, и придуманный рядом с ним не нужен.
 */

import type { FrpLevel } from './frp/catalog';

// Нормативные ссылки в творительном падеже: оборот «в соответствии с …».
const FZ_273_INSTR =
  'Федеральным законом от 29.12.2012 № 273-ФЗ «Об образовании в Российской Федерации» (в действующей редакции)';
const FGOS_INSTR: Record<FrpLevel, string> = {
  НОО: 'приказом Минпросвещения России от 31.05.2021 № 286 (ФГОС НОО)',
  ООО: 'приказом Минпросвещения России от 31.05.2021 № 287 (ФГОС ООО)',
  СОО: 'приказом Минобрнауки России от 17.05.2012 № 413 (ФГОС СОО, в действующей редакции)',
};
const FOP_ORDER: Record<FrpLevel, string> = {
  НОО: '(приказ Минпросвещения России от 18.05.2023 № 372)',
  ООО: '(приказ Минпросвещения России от 18.05.2023 № 370)',
  СОО: '(приказ Минпросвещения России от 18.05.2023 № 371)',
};

export function generateNormativeBase(level: FrpLevel, subject: string): string {
  return (
    `Рабочая программа по учебному предмету «${subject}» разработана в соответствии с:\n` +
    `— ${FZ_273_INSTR};\n` +
    `— ${FGOS_INSTR[level]};\n` +
    `— федеральной образовательной программой ${FOP_ORDER[level]}, включая федеральную ` +
    `рабочую программу по учебному предмету «${subject}»;\n` +
    '— положением о рабочей программе образовательной организации.'
  );
}
