/**
 * Нормы часов, изменённые приказами уже после публикации ФРП.
 *
 * Каталог собран из программ, выложенных ИСРО в июле 2025 года. Приказы
 * Минпросвещения России от 08.10.2025 № 729 и от 10.11.2025 № 808 вышли позже,
 * а программы ИСРО не переиздал, поэтому расхождение снимается здесь.
 *
 * Всё, что приказы поменяли в содержании программ, попадает в каталог при
 * сборке (tools/frp_orders.py). Здесь остаётся только то, чего в тексте
 * программ нет: годовая норма часов — она задана учебным планом, а не ФРП.
 *
 * **Норма привязана к учебному году программы, а не к сегодняшней дате.**
 * Программу на 2026/2027 пишут в мае-августе 2026 года, то есть до вступления
 * приказа в силу, — и норму надо ставить ту, что будет действовать в этом
 * учебном году, а не ту, что действует в день заполнения.
 *
 * **Конструктор не решает за учителя.** Оба числа, старое и новое, считаются
 * допустимыми: расхождение не помечается ошибкой, а рядом висит предупреждение
 * со ссылкой на документ. Сколько часов встанет в программу, решает учитель —
 * по учебному плану своей школы.
 */

/** Приложение к письму Минпросвещения: изменения расписаны по классам. */
const LETTER_URL =
  'https://edsoo.ru/wp-content/uploads/2026/03/03-320-prilozhenie-versiya-2.pdf';
const LETTER_LABEL = 'Письмо Минпросвещения от 02.03.2026 № 03-320 (изменения по классам)';

export interface OrderChange {
  /** Норма для учебного года программы; null — приказ часы не трогал. */
  hours: number | null;
  /** Второе допустимое значение: норма по другую сторону от приказа. */
  alsoAllowed: number | null;
  /** Нижняя граница, если приказ разрешил сокращать норму (адаптация 1 класса). */
  min: number | null;
  /** В учебном году программы действует уже новая норма. */
  inForce: boolean;
  /** Предупреждение для учителя. */
  text: string;
  docUrl: string;
  docLabel: string;
}

/**
 * Год начала учебного года из поля титульного листа: «2026-2027», «2026/2027»,
 * «2026 – 2027 учебный год» — везде первое четырёхзначное число. Если поле
 * очистили, считаем по дате: с августа идёт уже следующий учебный год.
 */
function startYear(academicYear: string): number {
  const found = academicYear.match(/\d{4}/);
  if (found) return Number(found[0]);
  const now = new Date();
  return now.getMonth() >= 7 ? now.getFullYear() : now.getFullYear() - 1;
}

/**
 * Иностранный язык на уровне ООО: 102 часа → 68.
 *
 * Приказ № 808 (подпункты 119–123 пункта 2 Изменений, одинаковый текст для
 * английского, немецкого, французского, испанского и китайского): «Общее число
 * часов, рекомендованных для изучения иностранного (английского) языка, —
 * 408 часов: в 5 классе — 68 часов (2 часа в неделю), в 6 классе — 68 часов
 * (в 2026/27 учебном году — 102 часа), в 7 классе — 68 часов (в 2026/27 учебном
 * году — 102 часа), в 8 классе — 102 часа, в 9 классе — 102 часа».
 *
 * Первым иностранным ИСРО публикует только три языка из пяти; второй
 * иностранный — отдельный предмет, приказ его не касается: там и было 68.
 *
 * Тематическое планирование остаётся прежним: новую редакцию ФРП с разбивкой
 * на 68 часов ИСРО не выложил (новость ЕДСОО от 13.07.2026: «шаблоны будут
 * опубликованы после утверждения изменений»), а придумывать распределение по
 * темам за министерство нельзя.
 */
const FOREIGN_LANGUAGE_OOO = new Set([
  'inostrannyj-anglijskij-yazyk-ooo',
  'inostrannyj-nemeckij-yazyk-ooo',
  'inostrannyj-francuzskij-yazyk-ooo',
]);

/** Класс → учебный год, с которого иностранный язык идёт по 2 часа в неделю. */
const TWO_HOURS_SINCE: Record<number, number> = { 5: 2026, 6: 2027, 7: 2027 };

export function orderChange(
  slug: string,
  grade: number,
  academicYear: string,
): OrderChange | null {
  const year = startYear(academicYear);

  if (FOREIGN_LANGUAGE_OOO.has(slug)) {
    const from = TWO_HOURS_SINCE[grade];
    if (!from) return null;
    const inForce = year >= from;
    return {
      hours: inForce ? 68 : 102,
      alsoAllowed: inForce ? 102 : 68,
      inForce,
      min: null,
      docUrl: LETTER_URL,
      docLabel: LETTER_LABEL,
      text:
        `С ${from}/${from + 1} учебного года иностранный язык в ${grade} классе — ` +
        '2 часа в неделю, 68 часов в год вместо 102 (приказ Минпросвещения России ' +
        'от 10.11.2025 № 808, зарегистрирован в Минюсте России 11.02.2026 № 85296). ' +
        (inForce
          ? `Программа у вас на ${from}/${from + 1} — подставлена новая норма, 68 ч. `
          : 'Программа у вас на более ранний год — подставлена прежняя норма, 102 ч. ') +
        'Федеральная рабочая программа с планированием на 68 часов ещё не ' +
        'опубликована (ЕДСОО, 13.07.2026: шаблоны выйдут после утверждения ' +
        'изменений), поэтому таблица заполняется прежней разбивкой на 102 ч — ' +
        'лишние часы придётся снять самостоятельно. Сверьтесь с учебным планом ' +
        'своей школы: и 102, и 68 часов конструктор считает допустимыми, ' +
        'сколько поставить — решаете вы.',
    };
  }

  /*
    Физическая культура на уровне СОО. Приказ № 729 (подпункт 9 пункта 2
    Изменений, пункт 127.5.12): «Общее число часов, рекомендованных для изучения
    физической культуры, — 136 часов: в 10 классе — 68 часов (2 часа в неделю),
    в 11 классе — 68 часов. Общее число часов, рекомендованных для изучения
    вариативных модулей физической культуры, — 68 часов: в 10 классе — 34 часа,
    в 11 классе — 34 часа. При этом число часов, рекомендованных для изучения
    физической культуры в рамках универсального профиля, — 204 часа: в 10 классе
    — 102 часа, в 11 классе — 102 часа». В самой ФРП осталось 102.
  */
  if (slug === 'fizicheskaya-kultura-soo' && (grade === 10 || grade === 11)) {
    return {
      hours: 68,
      alsoAllowed: 102,
      min: null,
      inForce: true,
      docUrl: LETTER_URL,
      docLabel: LETTER_LABEL,
      text:
        `Норма часов изменена: в ${grade} классе — 68 часов (2 часа в неделю) ` +
        'плюс 34 часа вариативных модулей; 102 часа остались только в ' +
        'универсальном профиле (приказ Минпросвещения России от 08.10.2025 ' +
        '№ 729, пункт 127.5.12). В самой федеральной программе по-прежнему ' +
        'стоит 102 часа, поэтому таблица заполняется её разбивкой. ' +
        'Конструктор считает допустимыми оба числа — выберите то, что стоит ' +
        'в учебном плане вашей школы.',
    };
  }

  /*
    Обществознание, 11 класс. Переходный год: 10 класс с 01.09.2026 учится по
    новой программе (приказ № 729, пункт 123-1), а 11 класс до 01.09.2027
    доучивается по прежней — она и лежит в каталоге. С 2027/2028 года 11 класс
    переходит на новую программу, и часов там 34, а не 68.
  */
  if (slug === 'obschestvoznanie-soo-bazovyj' && grade === 11) {
    const inForce = year >= 2027;
    return {
      hours: inForce ? 34 : 68,
      alsoAllowed: inForce ? 68 : 34,
      inForce,
      min: null,
      docUrl: LETTER_URL,
      docLabel: LETTER_LABEL,
      text:
        'С 2027/2028 учебного года 11 класс переходит на новую программу по ' +
        'обществознанию — 1 час в неделю, 34 часа (приказ Минпросвещения России ' +
        'от 08.10.2025 № 729). ' +
        (inForce
          ? 'Программа у вас на этот год или позже — подставлено 34 ч, но в ' +
            'таблице по-прежнему прежний, 68-часовой план: содержание новой ' +
            'программы 11 класса войдёт в конструктор к этому сроку.'
          : 'В вашем учебном году 11 класс ещё доучивается по прежней программе — ' +
            'она в конструкторе и лежит, 68 часов.'),
    };
  }

  /*
    Первый класс, адаптационный период. Приказ № 729 разрешил сокращать годовую
    норму в сентябре и октябре, когда идёт по 3 урока в день: у каждого предмета
    свой потолок сокращения, содержание при этом не сокращается. Физическую
    культуру сокращать не рекомендовано (письмо от 02.03.2026 № 03-320).
    Норму конструктор не меняет — это решение школы; допустимым становится
    любое число часов от нижней границы до нормы ФРП.
  */
  const cut = FIRST_GRADE_CUT[slug];
  if (cut && grade === 1) {
    const norm = FIRST_GRADE_HOURS[slug];
    const min = Math.ceil(norm * (1 - cut / 100));
    return {
      hours: null,
      alsoAllowed: null,
      min,
      inForce: true,
      docUrl: LETTER_URL,
      docLabel: LETTER_LABEL,
      text:
        `На адаптационный период — сентябрь и октябрь, когда в 1 классе по три ` +
        `урока в день, — годовую норму разрешено сократить не более чем на ${cut}% ` +
        `(приказ Минпросвещения России от 08.10.2025 № 729): с ${norm} до ${min} часов. ` +
        'Содержание предмета при этом не сокращается, а решение принимает школа — ' +
        `поэтому конструктор считает допустимым любое число часов от ${min} до ${norm}.`,
    };
  }

  return null;
}

/** Предельное сокращение годовой нормы в 1 классе, процентов. */
const FIRST_GRADE_CUT: Record<string, number> = {
  'russkij-yazyk-noo': 6,
  'literaturnoe-chtenie-noo': 3,
  'matematika-noo': 6,
  'okruzhayuschij-mir-noo': 12,
  'izobrazitelnoe-iskusstvo-noo': 12,
  'muzyka-noo': 12,
  'trud-tehnologiya-noo': 12,
};

/** Годовая норма 1 класса по ФРП — та же, что в каталоге. */
const FIRST_GRADE_HOURS: Record<string, number> = {
  'russkij-yazyk-noo': 165,
  'literaturnoe-chtenie-noo': 132,
  'matematika-noo': 132,
  'okruzhayuschij-mir-noo': 66,
  'izobrazitelnoe-iskusstvo-noo': 33,
  'muzyka-noo': 33,
  'trud-tehnologiya-noo': 33,
};
