/**
 * Цели Яндекс.Метрики.
 *
 * Счётчик инициализируется в index.html, здесь только отправка событий.
 * Считать по просмотрам страниц тут нечего: адрес у приложения один на всю
 * работу, и «зашёл посмотреть» неотличимо от «сделал программу и скачал».
 * Поэтому отмечаем два перелома пути — программа заполнена и файл сохранён.
 *
 * ponytail: ни очереди, ни повторной отправки. Не ушедшая цель — минус точка
 * в отчёте; ронять из-за аналитики выгрузку, которую учитель ждал, нельзя.
 */

declare global {
  interface Window {
    ym?: (counter: number, action: string, ...rest: unknown[]) => void;
  }
}

/** Тот же счётчик, что в index.html и на портале, — иначе рвётся воронка «лендинг → приложение». */
const COUNTER = 108745963;

/**
 * `window.ym` может не быть: на localhost инициализация в index.html
 * пропускается намеренно, у части посетителей счётчик режет блокировщик.
 */
export function goal(name: string, params?: Record<string, string>): void {
  try {
    window.ym?.(COUNTER, 'reachGoal', name, params);
  } catch (e) {
    console.warn('Метрика: цель не отправлена', name, e);
  }
}
